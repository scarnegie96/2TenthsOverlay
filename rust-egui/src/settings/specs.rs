//! Every widget's description and option controls (label, help, range,
//! choices): the Rust copy of `WIDGETS` in `src/lib/config.ts`, generated from
//! it (a test checks the defaults against `schema.rs`). Keep the two in step.

#[derive(Debug, Clone, Copy)]
pub struct Choice {
    pub value: &'static str,
    pub label: &'static str,
    pub help: Option<&'static str>,
}

#[derive(Debug, Clone, Copy)]
pub enum Kind {
    Toggle,
    Number { min: f64, max: f64, step: f64, suffix: Option<&'static str> },
    Select(&'static [Choice]),
    Text { max_length: Option<usize> },
}

#[derive(Debug, Clone, Copy)]
pub struct OptionSpec {
    pub key: &'static str,
    pub label: &'static str,
    pub help: Option<&'static str>,
    pub kind: Kind,
}

#[derive(Debug, Clone, Copy)]
pub struct WidgetSpec {
    pub id: &'static str,
    pub description: &'static str,
    pub experimental: bool,
    pub options: &'static [OptionSpec],
}

